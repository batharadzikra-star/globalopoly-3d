export function calculateCountryRent(tile: TileConfig, builtFacilities: FacilityId[] = []): number {
  const base = tile.baseRent ?? 30;
  const bonus = builtFacilities.reduce((acc, fid) => acc + (FACILITIES[fid]?.rentBonus ?? 0), 0);
  return base + bonus;
}

export function calculateCountryAssetValue(tile: TileConfig, builtFacilities: FacilityId[] = []): number {
  const basePrice = tile.price ?? 0;
  const facilitiesValue = builtFacilities.reduce(
    (acc, fid) => acc + Math.round(basePrice * (FACILITIES[fid]?.costMultiplier ?? 0)),
    0,
  );
  return basePrice + facilitiesValue;
}
